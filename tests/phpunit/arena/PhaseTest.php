declare(strict_types=1);

namespace LatamPMDevs\minerware\arena;

use LatamPMDevs\minerware\arena\phase\EndingPhase;
use LatamPMDevs\minerware\arena\phase\InbetweenPhase;
use LatamPMDevs\minerware\arena\phase\IngamePhase;
use LatamPMDevs\minerware\arena\phase\StartingPhase;
use LatamPMDevs\minerware\arena\phase\WaitingPhase;
use PHPUnit\Framework\TestCase;

final class PhaseTest extends TestCase {

	public function testOnlyTheWaitingPhasesAreLobbies() : void {
		self::assertTrue(WaitingPhase::getInstance()->isLobby());
		self::assertTrue(StartingPhase::getInstance()->isLobby());
		self::assertFalse(InbetweenPhase::getInstance()->isLobby());
		self::assertFalse(IngamePhase::getInstance()->isLobby());
		self::assertFalse(EndingPhase::getInstance()->isLobby());
	}

	public function testTimedPhasesHaveADuration() : void {
		self::assertSame(5, InbetweenPhase::getInstance()->getDuration());
		self::assertSame(10, EndingPhase::getInstance()->getDuration());
		self::assertSame(0, IngamePhase::getInstance()->getDuration());
	}

	public function testPhasesAreShared() : void {
		self::assertSame(WaitingPhase::getInstance(), WaitingPhase::getInstance());
	}
}
