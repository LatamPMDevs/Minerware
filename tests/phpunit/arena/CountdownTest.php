declare(strict_types=1);

namespace LatamPMDevs\minerware\arena;

use PHPUnit\Framework\TestCase;

final class CountdownTest extends TestCase {

	public function testResetSetsRemainingAndTotal() : void {
		$countdown = new Countdown();
		$countdown->reset(10);
		$countdown->decrement();
		self::assertSame(9, $countdown->getRemaining());
		self::assertSame(10, $countdown->getTotal());
	}

	public function testSetKeepsTotal() : void {
		$countdown = new Countdown();
		$countdown->reset(120);
		$countdown->set(5);
		self::assertSame(5, $countdown->getRemaining());
		self::assertSame(120, $countdown->getTotal());
	}

	public function testPauseIsIndependentOfTime() : void {
		$countdown = new Countdown();
		self::assertFalse($countdown->isPaused());
		$countdown->setPaused(true);
		$countdown->reset(3);
		self::assertTrue($countdown->isPaused());
	}
}
