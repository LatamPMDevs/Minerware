declare(strict_types=1);

namespace LatamPMDevs\minerware\arena\microgame;

use pocketmine\event\block\BlockBreakEvent;
use pocketmine\event\block\BlockPlaceEvent;

/**
 * Cancels block breaking and placing for the players of the arena.
 *
 * @property \LatamPMDevs\minerware\arena\Arena $arena
 */
trait CancelsBuildEvents {

	public function onBlockBreak(BlockBreakEvent $event) : void {
		if ($this->arena->inGame($event->getPlayer())) {
			$event->cancel();
		}
	}

	public function onBlockPlace(BlockPlaceEvent $event) : void {
		if ($this->arena->inGame($event->getPlayer())) {
			$event->cancel();
		}
	}
}
