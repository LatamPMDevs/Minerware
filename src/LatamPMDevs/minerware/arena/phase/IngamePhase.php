declare(strict_types=1);

namespace LatamPMDevs\minerware\arena\phase;

use LatamPMDevs\minerware\arena\Arena;
use pocketmine\utils\SingletonTrait;

/**
 * The microgame ticks itself (see Arena::tickMicrogame()); this only notices it ended.
 */
final class IngamePhase extends PlayingPhase {
	use SingletonTrait;

	public function getName() : string {
		return "ingame";
	}

	public function tick(Arena $arena) : void {
		if ($arena->getCurrentMicrogame() === null) {
			$arena->setPhase(InbetweenPhase::getInstance());
		}
	}

	protected function getMicrogameLine(Arena $arena) : string {
		return "§e" . ($arena->getCurrentMicrogame()?->getName() ?? "");
	}
}