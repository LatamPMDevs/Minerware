declare(strict_types=1);

namespace LatamPMDevs\minerware\entity;

use pocketmine\player\Player;
use function microtime;

/**
 * Players who asked to remove an NPC or the leaderboard: their next hit or click on one removes it.
 */
final class PendingRemovals {

	private const WINDOW = 10.0; //seconds

	/** @var array<int, float> player id => seconds (microtime) when the request expires */
	private array $expiries = [];

	public function arm(Player $player) : void {
		$this->expiries[$player->getId()] = microtime(true) + self::WINDOW;
	}

	public function consume(Player $player) : bool {
		$expiry = $this->expiries[$player->getId()] ?? null;
		unset($this->expiries[$player->getId()]);
		return $expiry !== null && $expiry >= microtime(true);
	}
}
